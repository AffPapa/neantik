#!/usr/bin/env python3
"""Reproduce the pinned .80 sign_config action in an isolated package.

This is not a build, a signature, or release qualification.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "runtime/chromium-15680-signing-package-inputs.json"


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while chunk := f.read(1024 * 1024):
            h.update(chunk)
    return h.hexdigest()


def prepare(source: Path, out: Path, destination: Path, spec: dict) -> None:
    package = out / "NeAntik Browser Packaging"
    if not source.is_absolute() or not out.is_absolute() or not destination.is_absolute():
        raise ValueError("paths must be absolute")
    if destination.exists() or destination.is_symlink():
        raise ValueError("destination already exists")
    if spec.get("schemaVersion") != 1 or spec.get("chromiumVersion") != "156.0.8078.80":
        raise ValueError("unsupported signing inputs")
    if sha(out / "toolchain.ninja") != spec["toolchainNinjaSHA256"]:
        raise ValueError("Ninja action graph changed")
    for name, digest in spec["generatorInputs"].items():
        path = source / name
        if path.is_symlink() or not path.is_file() or sha(path) != digest:
            raise ValueError("generator input changed: " + name)
    found = {}
    for parent, dirs, files in os.walk(package, followlinks=False):
        for name in dirs:
            if (Path(parent) / name).is_symlink():
                raise ValueError("signing package contains a directory symlink")
        for name in files:
            path = Path(parent) / name
            info = os.lstat(path)
            if not stat.S_ISREG(info.st_mode):
                raise ValueError("signing package contains a non-regular file")
            found[path.relative_to(package).as_posix()] = {
                "sha256": sha(path), "mode": stat.S_IMODE(info.st_mode)
            }
    if found != spec["files"]:
        raise ValueError("signing package differs from pinned inputs")
    shutil.copytree(package, destination, symlinks=False)
    for name, expected_file in spec["files"].items():
        copied = destination / name
        info = os.lstat(copied)
        if (not stat.S_ISREG(info.st_mode) or sha(copied) != expected_file["sha256"]
                or stat.S_IMODE(info.st_mode) != expected_file["mode"]):
            raise ValueError("copied signing input changed: " + name)
    config = destination / "signing/build_props_config.py"
    previous = config.read_bytes()
    command = [sys.executable, "-B", str(source / "build/util/version.py"), "--official",
        "-f", str(source / "chrome/VERSION"), "-f", str(source / "chrome/app/theme/chromium/BRANDING"),
        "-f", str(source / "build/util/LASTCHANGE"), "-e",
        'GEN_HEADER="THIS FILE IS AUTOMATICALLY GENERATED BY //chrome/installer/mac/sign_config:sign_config.\\n"',
        "-e", "IS_CHROME_BRANDED=False", "-e", "ENABLE_UPDATER=False", "-e", "USE_STATIC_ANGLE=True",
        "-o", str(config), str(source / "chrome/installer/mac/signing/build_props_config.py.in")]
    subprocess.run(command, cwd=out, check=True)
    generated = config.read_bytes()
    expected = previous.replace(b"return '156.0.8078.74'", b"return '156.0.8078.80'", 1)
    if generated != expected or sha(config) != spec["generatedConfigSHA256"]:
        raise ValueError("generated signing configuration is unexpected")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    try:
        prepare(args.source, args.out, args.destination, json.loads(MANIFEST.read_text()))
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"Isolated signing package refused: {error}")
    print("Isolated .80 signing package prepared; signing and qualification remain required.")


if __name__ == "__main__":
    main()
