#!/usr/bin/env python3
"""Generate NeAntik-owned TTFs for process-scoped QA; never install fonts.

Requires the pinned QA-only FontTools dependency, not a product dependency.
No system or user font is read or copied.
"""
import argparse
import hashlib
import json
from pathlib import Path
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen


def build(output, family, postscript):
    font = FontBuilder(1000, isTTF=True)
    font.setupGlyphOrder(['.notdef','space','canary'])
    font.setupCharacterMap({32:'space',65:'canary',66:'canary',0xE000:'canary'})
    glyphs = {}
    for name in ['.notdef','space','canary']:
        pen = TTGlyphPen(None)
        if name != 'space':
            pen.moveTo((50,0));pen.lineTo((650,0));pen.lineTo((650,700));pen.lineTo((50,700));pen.closePath()
        glyphs[name] = pen.glyph()
    font.setupGlyf(glyphs)
    font.setupHorizontalMetrics({name:(730,0) for name in glyphs})
    font.setupHorizontalHeader(ascent=800,descent=-200)
    font.setupNameTable({'familyName':family,'styleName':'Regular','uniqueFontIdentifier':postscript+'-own-v1',
                        'fullName':family+' Regular','psName':postscript,'version':'Version 1.0'})
    font.setupOS2(sTypoAscender=800,sTypoDescender=-200,usWinAscent=800,usWinDescent=200)
    font.setupPost()
    font.font['head'].created = 2082844800
    font.font['head'].modified = 2082844800
    font.font.recalcTimestamp = False
    font.save(output)
    output.chmod(0o600)
    return {'name':output.name,'sha256':hashlib.sha256(output.read_bytes()).hexdigest(),'bytes':output.stat().st_size}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('output',type=Path);args=parser.parse_args()
    assert args.output.is_absolute() and args.output.is_dir() and not any(args.output.iterdir())
    results=[build(args.output/'owned-canary.ttf','NeAntik Font Policy Canary','NeAntikFontPolicyCanary'),
             build(args.output/'owned-family-collision.ttf','Helvetica','NeAntikFontPolicyFamilyCollision')]
    (args.output/'canary-manifest.json').write_text(json.dumps({'source':'Original simple outline generated by NeAntik QA; no existing font copied','fonts':results},indent=2)+'\n')
    print(json.dumps({'created':len(results),'systemFontsRead':False,'installed':False}))
