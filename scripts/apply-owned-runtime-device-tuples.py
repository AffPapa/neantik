def atomic_write(path: Path, data: bytes, *, mode: int) -> None:
    temporary = path.with_name(f".{path.name}.neantik-tuples")
    temporary.write_bytes(data)
    os.chmod(temporary, mode)
    os.replace(temporary, path)


def rendered_postimages(source_root: Path) -> dict[str, bytes]:
    tuples = CATALOG_LOADER.load_device_tuples(CATALOG_PATH)
    rendered = {HEADER_PATH: render_header(tuples).encode("utf-8")}
    for relative, transform in TRANSFORMS.items():
        path = source_root / relative
        try:
            original = path.read_bytes()
        except OSError as error:
            raise OwnedDeviceTupleError(
                f"missing Chromium source file: {relative}"
            ) from error
        actual = sha256_bytes(original)
        expected_postimage = POSTIMAGE_SHA256[relative]
        if actual == expected_postimage:
            rendered[relative] = original
            continue
        if actual != PREIMAGE_SHA256[relative]:
            raise OwnedDeviceTupleError(
                f"{relative}: unexpected preimage SHA-256 {actual}"
            )
        try:
            rendered[relative] = transform(original.decode("utf-8")).encode(
                "utf-8"
            )
        except UnicodeDecodeError as error:
            raise OwnedDeviceTupleError(
                f"{relative}: source is not UTF-8"
            ) from error
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Generate and apply the canonical NeAntik Apple tuple overlay "
            "to an owned Chromium 150 source root."
        )
    )
    parser.add_argument("source_root", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--show-postimages", action="store_true")
    args = parser.parse_args()
    source_root = args.source_root.resolve()
    try:
        rendered = rendered_postimages(source_root)
    except (OwnedDeviceTupleError, CATALOG_LOADER.DeviceTupleCatalogError) as error:
        print(f"Owned device tuple overlay failed: {error}", file=sys.stderr)
        return 65

    actual_postimages = {
        relative: sha256_bytes(data)
        for relative, data in rendered.items()
    }
    if args.show_postimages:
        for relative in sorted(actual_postimages):
            print(f"{relative} {actual_postimages[relative]}")
        return 0

    mismatches = [
        f"{relative}: expected {POSTIMAGE_SHA256[relative]}, "
        f"rendered {actual_postimages[relative]}"
        for relative in sorted(actual_postimages)
        if actual_postimages[relative] != POSTIMAGE_SHA256[relative]
    ]
    if mismatches:
        print(
            "Owned device tuple overlay postimages are not reviewed:\n"
            + "\n".join(mismatches),
            file=sys.stderr,
        )
        return 65

    if args.check:
        for relative, data in rendered.items():
            path = source_root / relative
            if not path.is_file() or path.read_bytes() != data:
                print(
                    f"Owned device tuple overlay is not applied: {relative}",
                    file=sys.stderr,
                )
                return 65
        print(
            "Owned Chromium Apple device tuple overlay verified: "
            f"{len(rendered)} postimages."
        )
        return 0

    for relative, data in rendered.items():
        path = source_root / relative
        if path.is_file() and path.read_bytes() == data:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        mode = path.stat().st_mode if path.exists() else 0o644
        atomic_write(path, data, mode=mode)
        print(f"APPLY {relative}")
    print(
        "Owned Chromium Apple device tuple overlay applied: "
        f"{len(rendered)} postimages."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
