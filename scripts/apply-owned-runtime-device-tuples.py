class OwnedDeviceTupleError(ValueError):
    pass


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def replace_once(text: str, before: str, after: str, *, label: str) -> str:
    count = text.count(before)
    if count != 1:
        raise OwnedDeviceTupleError(
            f"{label}: expected one exact preimage, found {count}"
        )
    return text.replace(before, after, 1)


def render_header(tuples: list[object]) -> str:
    rows: list[str] = []
    for item in tuples:
        rows.append(
            "    {"
            f'"{item.id}", "{item.gpu_model}", '
            f"{item.hardware_concurrency}, {item.physical_memory_gb}, "
            f"{item.web_device_memory_gb}, "
            f"{item.screen_width}, {item.screen_height}, "
            f"{item.available_width}, {item.available_height}, "
            f"{item.color_depth}, {item.device_scale_factor}, "
            f'"{item.platform_version}"'
            "},"
        )
    return (
        "// Generated by apply-owned-runtime-device-tuples.py.\n"
        "// Source: runtime/apple-device-tuples.json. Do not edit by hand.\n"
        "#ifndef COMPONENTS_UNGOOGLED_NEANTIK_APPLE_DEVICE_TUPLES_H_\n"
        "#define COMPONENTS_UNGOOGLED_NEANTIK_APPLE_DEVICE_TUPLES_H_\n\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        "namespace ungoogled::nevision {\n\n"
        "struct AppleDeviceTuple {\n"
        "  const char* id;\n"
        "  const char* gpu_model;\n"
        "  unsigned hardware_concurrency;\n"
        "  unsigned physical_memory_gb;\n"
        "  unsigned web_device_memory_gb;\n"
        "  int screen_width;\n"
        "  int screen_height;\n"
        "  int available_width;\n"
        "  int available_height;\n"
        "  unsigned color_depth;\n"
        "  double device_scale_factor;\n"
        "  const char* platform_version;\n"
        "};\n\n"
        "inline constexpr AppleDeviceTuple kAppleDeviceTuples[] = {\n"
        + "\n".join(rows)
        + "\n};\n\n"
        "inline constexpr size_t kAppleDeviceTupleCount =\n"
        "    sizeof(kAppleDeviceTuples) / sizeof(kAppleDeviceTuples[0]);\n\n"
        "inline const AppleDeviceTuple& GetAppleDeviceTuple(uint32_t seed) {\n"
        "  return kAppleDeviceTuples[seed % kAppleDeviceTupleCount];\n"
        "}\n\n"
        "}  // namespace ungoogled::nevision\n\n"
        "#endif  // COMPONENTS_UNGOOGLED_NEANTIK_APPLE_DEVICE_TUPLES_H_\n"
    )


def transform_hardware(text: str) -> str:
    text = replace_once(
        text,
        '#include "components/ungoogled/nevision_fingerprint.h"\n',
        '#include "components/ungoogled/neantik_apple_device_tuples.h"\n'
        '#include "components/ungoogled/nevision_fingerprint.h"\n',
        label="hardware include",
    )
    return replace_once(
        text,
        "  if (ungoogled::nevision::GetProfileSeed().has_value()) {\n"
        "    constexpr unsigned kAppleSiliconHardwareConcurrency[] = {8, 10, 8, 12, 12};\n"
        "    return kAppleSiliconHardwareConcurrency[ungoogled::nevision::GetProfileByte(\n"
        "        \"apple-device-tuple\", 0, (sizeof(kAppleSiliconHardwareConcurrency) / sizeof(kAppleSiliconHardwareConcurrency[0])))];\n"
        "  }\n",
        "  if (const auto seed = ungoogled::nevision::GetProfileSeed()) {\n"
        "    return ungoogled::nevision::GetAppleDeviceTuple(*seed)\n"
        "        .hardware_concurrency;\n"
        "  }\n",
        label="hardware tuple",
    )


